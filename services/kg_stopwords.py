"""kg_stopwords — KG 入库的停用词 / 结构词过滤（2026-09-13，B-014）。

## 为什么需要

原 RAG 语料经历过**第二轮清洗**（`tools/clean_pairs.py`：7075 → 4704 对），
因为"从每条消息无差别抽取"必然产出大量无信息量条目。KG 入库此前**完全没有
等价的那一道**，实测后果（`memory_store.db`，2026-09-13）：

| 指标 | 值 |
|---|---|
| distinct topic 实体 | **3194** 个 |
| 实体行（含重复） | 12541 |
| 出现 ≤1 次的实体 | 2119 个（**66.3%**） |
| `配图`/`识别`/`无法` | 1511 / 1289 / 1210 → 占实体行 **31.9%** |

那三个词是**我们自己的**识图占位符 `（配图：无法识别）` 被 jieba 切出来的 ——
即系统产物污染了自己的长期记忆。

## 三类过滤（按危害排序）

1. **系统结构词**：识图/表情/引用等占位符切出来的词。**必删** —— 它们是
   我们自己的输出格式，不是群友聊的内容。
2. **无信息量通用词**：`什么`/`怎么`/`今日`/`感觉` 等。jieba 的 `extract_tags`
   按 TF-IDF 取词，这类词在群聊语料里必然高频，但作为"话题"零价值。
3. **过短/纯符号/纯数字**：保留 `len >= 2` 的同时排除纯 ASCII 标点、纯数字串
   （QQ 号另有 member 通道）。

## 设计原则：宁可漏删，不可误删

群聊里 `老婆`/`戒色`/`签到` 这类**看起来像噪声但确实是群内梗**的词**必须保留**
（它们是真实话题）。所以这里只收录"确定无话题价值"的词，不做激进裁剪。
真实话题的进一步筛选交给"只出现一次不入图"的门槛（`MemoryStore.ingest`）。

## 与图片描述的关系

识图描述整段**不进 topic 抽取**（`ingest` 里按 `（配图：` 标记跳过）—— 描述是
"眼前信息"（给 RP 看这一轮发生了什么），不是"值得长期记住的话题"。
本表的 `配图`/`识别`/`无法` 只是**第二道保险**：防历史遗留与格式变体。
"""
from __future__ import annotations

import re
from typing import Iterable

# ---- 1. 系统结构词（我们自己的占位符/格式产物）----
SYSTEM_STRUCTURAL: frozenset[str] = frozenset({
    "配图", "识别", "无法", "图片", "表情", "引用", "消息", "消息记录",
    "组件", "附件", "文件", "链接", "合并", "转发", "闪传", "空消息",
    "表情包", "动图", "静图", "头像", "群聊", "私聊", "机器人",
})

# ---- 2. 无信息量通用词（高频但非话题）----
GENERIC_WORDS: frozenset[str] = frozenset({
    # 疑问/指示
    "什么", "怎么", "为什么", "为啥", "哪个", "哪些", "哪里", "哪儿",
    "这个", "那个", "这些", "那些", "这样", "那样", "这里", "那里",
    "怎么样", "怎么办", "多少", "几个",
    # 时间泛词（"今日/今天"本身不是话题，具体日期另论）
    "今日", "今天", "明天", "昨天", "现在", "刚才", "刚刚", "一会",
    "时候", "时间", "一会儿", "最近", "以后", "以前",
    # 语气/程度/连接
    "感觉", "觉得", "应该", "可能", "也许", "真的", "确实", "反正",
    "但是", "不过", "而且", "然后", "因为", "所以", "如果", "虽然",
    "还是", "就是", "已经", "一直", "有点", "非常", "特别", "比较",
    "可以", "不行", "没有", "不是", "知道", "不知", "什么鬼",
    # 社交泛词（不指向具体话题）
    "群友", "大家", "各位", "兄弟", "朋友", "同学", "老师",
    "哈哈", "哈哈哈", "呵呵", "嘻嘻", "嘿嘿", "emmm", "emmmm",
    "谢谢", "感谢", "辛苦", "加油", "好的", "收到", "明白",
})

# 注意：`晚安`/`早睡`/`签到`/`戒色` 这类词**刻意不删** —— 它们虽然高频，
# 但确实是群内行为/文化词（实测 `晚安`51 次 / `早睡`47 次 / `签到`70 次 /
# `戒色`54 次），删掉会损失真实信号。定表原则见模块 docstring：
# **宁可漏删，不可误删**；真正的噪声交给"只出现一次不入图"的门槛。

STOPWORDS: frozenset[str] = SYSTEM_STRUCTURAL | GENERIC_WORDS

# 纯数字（QQ 号 / 计数）、纯 ASCII 标点、单字符
_RE_PURE_DIGITS = re.compile(r"^\d+$")
_RE_PUNCT_ONLY = re.compile(r"^[\W_]+$", re.UNICODE)


def is_stopword(word: str) -> bool:
    """该词是否应被排除在 KG topic 之外。"""
    if not word:
        return True
    w = word.strip()
    if len(w) < 2:
        return True
    if w.lower() in STOPWORDS:
        return True
    if _RE_PURE_DIGITS.match(w):
        return True
    if _RE_PUNCT_ONLY.match(w):
        return True
    return False


def filter_keywords(words: Iterable[str]) -> list[str]:
    """过滤关键词序列（保序去重）。"""
    out: list[str] = []
    seen: set[str] = set()
    for w in words or ():
        w = (w or "").strip()
        if is_stopword(w) or w in seen:
            continue
        seen.add(w)
        out.append(w)
    return out


# 图片描述标记：文本含此串 → 整条不进 topic 抽取（描述是眼前信息，非长期话题）
IMAGE_DESC_MARKER = "（配图："


def carries_image_description(text: str) -> bool:
    """消息文本里是否含识图描述（含失败占位符）。

    两种形态都算：`（配图：<描述>）` 与 `（配图：无法识别）` —— 后者是识图
    失败占位，同样不该产出 topic。
    """
    return IMAGE_DESC_MARKER in str(text or "")
